"""Checks that the module version has a single source of truth.

module.prop is generated by build.py from its VERSION constant; the panel must
read the version from module.prop (via control.sh) and must never hardcode it.
"""
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
MODULE = HERE.parent
PANEL = MODULE / 'panel'
BUILD = MODULE / 'build.py'

failures = 0


def check(what, ok):
    global failures
    print(f"[{'ok' if ok else 'FAIL'}] {what}")
    if not ok:
        failures += 1


def build_version():
    match = re.search(r"^VERSION = '([^']+)'$", BUILD.read_text(encoding='utf-8'), re.M)
    return match.group(1) if match else None


def main():
    version = build_version()
    check('build.py declares a VERSION', bool(version))

    control = (PANEL / 'control.sh').read_text(encoding='utf-8')
    check('control.sh does not hardcode the version',
          version is not None and version not in control)
    check('control.sh reads version from module.prop',
          'module.prop' in control and 'module_version' in control)

    index = (PANEL / 'webroot/index.html').read_text(encoding='utf-8')
    check('index.html does not hardcode the version',
          version is not None and version not in index)
    # The version span must be populated at runtime, not baked in.
    check('index.html version span is empty at load',
          re.search(r'id="version"[^>]*></span>', index) is not None)

    app_js = (PANEL / 'webroot/app.js').read_text(encoding='utf-8')
    check('app.js derives the displayed version from module state',
          "state.version" in app_js)

    workflow = (MODULE.parents[1] / '.github/workflows/release.yml').read_text(encoding='utf-8')
    check('release.yml does not hardcode the version',
          version is not None and version not in workflow)
    check('release.yml does not use a branch ref as the release tag',
          'tag_name: ${{ github.ref_name }}' not in workflow)

    build = BUILD.read_text(encoding='utf-8')
    control = (PANEL / 'control.sh').read_text(encoding='utf-8')
    check('build.py generates the hma_plus_plus module id',
          "id=hma_plus_plus" in build)
    check('control.sh uses the same module id as build.py',
          'ID=hma_plus_plus' in control)
    check('control.sh stores config under the module id',
          'STORE=/data/adb/hma_plus_plus' in control)
    check('module name is HMA++',
          "name=HMA++" in build)
    check('module author is zeroedx',
          "author=zeroedx" in build)
    check('build.py names the ZIP after the module',
          'hma-plus-plus-{VERSION}' in build)

    print(f"\n{'VERSION TESTS FAILED' if failures else 'ALL VERSION TESTS PASSED'} ({failures} failures)")
    return 1 if failures else 0


if __name__ == '__main__':
    sys.exit(main())
